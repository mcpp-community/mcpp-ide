#!/usr/bin/env python3
"""Generates every editor-facing declaration from spec/, the single source.

    spec/settings.json          every setting: type, default, enum, bounds, group, title, description
    spec/commands.json          every command: id, title, category, icon, keys, menus, the JetBrains action
    spec/i18n/runtime.zh-cn.json  the runtime strings (English key -> Chinese)
    spec/i18n/manifest.*.json   the labels VS Code reads at startup (package.nls)

into

    src/generated/spec.cppm                     the backend: the settings registry and the runtime strings
    vscode/package.json (contributes)           commands, configuration, keybindings, menus
    vscode/package.nls.json, package.nls.zh-cn.json
    vscode/l10n/bundle.l10n.zh-cn.json
    jetbrains/src/main/resources/META-INF/mcpp-actions.xml
    jetbrains/src/main/resources/messages/McppBundle.properties, McppBundle_zh_CN.properties

`--check` writes nothing and fails when a generated file differs from what it
would write (CI's drift check).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec"


def load(name: str):
    return json.loads((SPEC / name).read_text(encoding="utf-8"))


def cpp_string(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def gen_backend(settings: dict, runtime_zh: dict) -> str:
    presets = load("presets.json")
    lines = [
        "// GENERATED by tools/generate.py from spec/; do not edit.",
        "export module mcppide.generated.spec;",
        "",
        "import std;",
        "",
        "export namespace mcppide::generated {",
        "",
        "struct Setting {",
        "    std::string_view key;",
        "    std::string_view type;         // boolean | string | number | array",
        "    std::string_view defaultJson;  // the default, as JSON",
        "    std::string_view enumJson;     // the allowed values, as a JSON array, or empty",
        "    std::string_view minimum, maximum;",
        "    std::string_view group, scope, applies, tier;",
        "    bool deprecated;",
        "    std::string_view aliasesJson;  // earlier keys of this setting",
        "    std::string_view title, description;",
        "};",
        "",
        "inline constexpr std::array kSettings = {",
    ]
    for s in settings["settings"]:
        enum = json.dumps(s["enum"], ensure_ascii=False) if "enum" in s else ""
        aliases = json.dumps(s.get("aliases", []), ensure_ascii=False)
        lines.append(
            "    Setting{"
            + ", ".join(
                [
                    cpp_string(s["key"]),
                    cpp_string(s["type"]),
                    cpp_string(json.dumps(s.get("default"), ensure_ascii=False)),
                    cpp_string(enum),
                    cpp_string(str(s["minimum"]) if "minimum" in s else ""),
                    cpp_string(str(s["maximum"]) if "maximum" in s else ""),
                    cpp_string(s.get("group", "")),
                    cpp_string(s.get("scope", "")),
                    cpp_string(s.get("applies", "")),
                    cpp_string(s.get("tier", "")),
                    "true" if s.get("deprecated") else "false",
                    cpp_string(aliases),
                    cpp_string(s.get("title", "")),
                    cpp_string(s.get("description", "")),
                ]
            )
            + "},"
        )
    lines += ["};", "", "struct Translation { std::string_view en, zh; };", "", "inline constexpr std::array kZhCn = {"]
    for en, zh in sorted(runtime_zh.items()):
        lines.append(f"    Translation{{{cpp_string(en)}, {cpp_string(zh)}}},")
    lines += ["};", "", "// spec/toml-schema.json and spec/buildscript-api.json, as JSON (mcpp's",
              "// manifest keys and build-program directives, snapshotted from an mcpp checkout).",
              "inline constexpr std::string_view kTomlSchemaJson = R\"mcppide(" + json.dumps(load("toml-schema.json"), ensure_ascii=False) + ")mcppide\";",
              "inline constexpr std::string_view kBuildScriptApiJson = R\"mcppide(" + json.dumps(load("buildscript-api.json"), ensure_ascii=False) + ")mcppide\";",
              "", "// spec/presets.json, as JSON.",
              "inline constexpr std::string_view kPresetsJson = " + cpp_string(json.dumps(presets, ensure_ascii=False)) + ";",
              "", "}  // namespace mcppide::generated", ""]
    return "\n".join(lines)


def write(path: Path, text: str, check: bool, drift: list[str]) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return
    if check:
        drift.append(str(path.relative_to(ROOT)))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    settings = load("settings.json")
    runtime_zh = load("i18n/runtime.zh-cn.json")
    drift: list[str] = []
    write(ROOT / "src/generated/spec.cppm", gen_backend(settings, runtime_zh), args.check, drift)
    for extra in GENERATORS:
        for path, text in extra(settings, runtime_zh):
            write(ROOT / path, text, args.check, drift)
    if drift:
        print("generated files differ from spec/ (run tools/generate.py):", *drift, sep="\n  ")
        return 1
    return 0


# The editor generators register themselves here (tools/generate_editors.py).
GENERATORS: list = []
try:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import generate_editors  # noqa: E402

    GENERATORS.extend(generate_editors.GENERATORS)
except ImportError:
    pass

if __name__ == "__main__":
    sys.exit(main())
